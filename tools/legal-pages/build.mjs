// Builds /privacy.html from the privacy policy inside index.html, so the policy has ONE source.
// Why: the policy on the site opens inside the one-page app and has no address of its own. The App Store,
// Google Play and the phone apps need a public address that shows the policy as plain HTML, with no script.
//
// Run:  node tools/legal-pages/build.mjs      (writes privacy.html at the repo root)
//       node tools/legal-pages/build.mjs --check   (fails when privacy.html is out of date)
// Run it again after ANY change to the priv.* strings or the privacy block in index.html.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const src = readFileSync(join(ROOT, 'index.html'), 'utf8').replace(/\r\n/g, '\n');

// 1. The policy's markup (headings, paragraphs, list) as it stands in index.html.
const start = src.indexOf('<div class="legal-page" id="privacyPage">');
const end = src.indexOf('<!-- LOADING -->', start);
if (start < 0 || end < 0) throw new Error('privacy block not found in index.html');
const block = src.slice(start, end);

// 2. Every priv.* string, in file order: the English dictionary comes first, the French one second.
const dict = { en: {}, fr: {} };
const re = /(['"])(priv\.[A-Za-z0-9]+)\1\s*:\s*(['"])((?:\\.|(?!\3)[^\\])*)\3/g;
for (let m; (m = re.exec(src)); ) {
  const value = m[4].replace(/\\(['"\\])/g, '$1');
  if (!(m[2] in dict.en)) dict.en[m[2]] = value;
  else if (!(m[2] in dict.fr)) dict.fr[m[2]] = value;
  else throw new Error('more than two definitions of ' + m[2]);
}

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// 3. Walk the markup and print each element with the string of the wanted language.
function render(lang) {
  const out = [];
  const el = /<(h1|h2|p|li)(?: class="meta")? data-i18n="(priv\.[A-Za-z0-9]+)">|<(\/?ul)>/g;
  for (let m; (m = el.exec(block)); ) {
    if (m[3]) { out.push(`<${m[3]}>`); continue; }
    const text = dict[lang][m[2]];
    if (typeof text !== 'string' || !text) throw new Error(`missing ${lang} text for ${m[2]}`);
    const cls = m[2] === 'priv.updated' ? ' class="meta"' : '';
    out.push(`<${m[1]}${cls}>${esc(text)}</${m[1]}>`);
  }
  return out.join('\n    ');
}
const used = new Set([...block.matchAll(/data-i18n="(priv\.[A-Za-z0-9]+)"/g)].map((m) => m[1]));
for (const k of used) if (!(k in dict.en) || !(k in dict.fr)) throw new Error('no translation pair for ' + k);

const html = `<!doctype html>
<!-- Generated by tools/legal-pages/build.mjs from the privacy policy in index.html. Do not edit by hand. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Privacy Policy | Politique de confidentialité · PunchClock Crew</title>
<meta name="description" content="What PunchClock Crew collects on the website and in the phone apps, why, and how to have it deleted.">
<link rel="canonical" href="https://www.punchclock.ca/privacy.html">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<style>
:root{color-scheme:light dark;--bg:#fff;--text:#1b2a5c;--text2:#3d4663;--accent:#1b2a5c;--line:#e3e6ef}
@media (prefers-color-scheme:dark){:root{--bg:#0f1629;--text:#f2f4fa;--text2:#c3c9da;--accent:#ffb020;--line:#263050}}
body{margin:0;background:var(--bg);color:var(--text);font:16px/1.7 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}
main{max-width:760px;margin:0 auto;padding:32px 20px 72px}
nav{display:flex;gap:16px;flex-wrap:wrap;font-size:14px;margin-bottom:24px}
a{color:var(--accent)}
h1{font-size:28px;margin:0 0 4px}
h2{font-size:17px;margin:28px 0 8px;color:var(--accent)}
p,li{color:var(--text2);font-size:15px;margin:0 0 8px}
.meta{font-size:13px;margin-bottom:28px}
section+section{border-top:1px solid var(--line);margin-top:48px;padding-top:32px}
</style>
</head>
<body>
<main>
  <nav><a href="/">PunchClock Crew</a><a href="#en">English</a><a href="#fr">Français</a><a href="/delete-account.html">Delete an account · Supprimer un compte</a></nav>
  <section id="en" lang="en">
    ${render('en')}
  </section>
  <section id="fr" lang="fr">
    ${render('fr')}
  </section>
</main>
</body>
</html>
`;
// --check: change nothing, fail when privacy.html no longer matches the policy in index.html (run before a push).
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(join(ROOT, 'privacy.html'), 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing */ }
  if (current !== html) { console.error('privacy.html is out of date: run node tools/legal-pages/build.mjs'); process.exit(1); }
  console.log('privacy.html matches index.html');
} else {
  writeFileSync(join(ROOT, 'privacy.html'), html);
  console.log(`privacy.html written: ${used.size} strings per language`);
}
